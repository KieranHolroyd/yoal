import { promises as fs } from 'node:fs';
import { join } from 'node:path';
import type { CommandRunner } from './systemd.ts';
import { CLOUD_SHELL_ID, ValidationError } from './validate.ts';

/**
 * Cloud shell (D236, docs/CLOUD-SHELL.md): a person's terminal container with a home disk.
 *
 * The disk is a real ext4 filesystem in a sparse image file under the shell's state directory
 * (`<stateDir>/<csh_id>/home.ext4`), loop-mounted by a systemd `.mount` unit at
 * `<stateDir>/<csh_id>/home` and bind-mounted into the container at `/home/yoal`. A filesystem
 * of its own is what makes "1 GiB" a limit rather than a reservation: a full disk fails the
 * person's writes, never the node's. The container unit requires the mount (`RequiresMountsFor=`),
 * so after a reboot the shell cannot start on the bare mountpoint and fill the root disk.
 */

export const CLOUD_SHELL_HOME = '/home/yoal';
export const CLOUD_SHELL_IMAGE_FILE = 'home.ext4';
export const CLOUD_SHELL_MOUNT_DIR = 'home';
/** The shell's /tmp: a tmpfs, counted against its memory limit. */
export const CLOUD_SHELL_TMP_MB = 256;

export interface CloudShellDiskPaths {
	/** `<stateDir>/<id>`: what `purge` deletes. */
	dir: string;
	image: string;
	mountPoint: string;
}

export function cloudShellDiskPaths(stateDir: string, id: string): CloudShellDiskPaths {
	if (!CLOUD_SHELL_ID.test(id)) throw new ValidationError('cloud shell ids look like csh_…');
	const dir = join(stateDir, id);
	return { dir, image: join(dir, CLOUD_SHELL_IMAGE_FILE), mountPoint: join(dir, CLOUD_SHELL_MOUNT_DIR) };
}

/**
 * `systemd-escape --path`: the unit name systemd requires for a `.mount` unit at `path`. Slashes
 * become `-`; anything but `[A-Za-z0-9:_.]`, and a `.` at the very start, becomes `\xNN` per
 * UTF-8 byte (systemd's `unit_name_path_escape`).
 */
export function systemdEscapePath(path: string): string {
	const trimmed = path.replace(/\/+/g, '/').replace(/^\/|\/$/g, '');
	if (trimmed === '') return '-';
	for (const segment of trimmed.split('/'))
		if (segment === '.' || segment === '..') throw new ValidationError(`Cannot escape a path with "${segment}" in it`);
	let escaped = '';
	const bytes = Buffer.from(trimmed, 'utf8');
	for (let index = 0; index < bytes.length; index++) {
		const byte = bytes[index]!;
		const char = String.fromCharCode(byte);
		if (char === '/') escaped += '-';
		else if (byte < 0x80 && /[A-Za-z0-9:_.]/.test(char) && !(index === 0 && char === '.')) escaped += char;
		else escaped += `\\x${byte.toString(16).padStart(2, '0')}`;
	}
	return escaped;
}

export function homeMountUnitName(mountPoint: string): string {
	return `${systemdEscapePath(mountPoint)}.mount`;
}

/** The `.mount` unit for one shell's home disk. Pulled in by the shell's container unit only. */
export function renderHomeMountUnit(options: { id: string; image: string; mountPoint: string }): string {
	return [
		'# Generated by yoal-helper. Do not edit; changes are overwritten.',
		'[Unit]',
		`Description=Yoal cloud shell ${options.id} home disk`,
		'DefaultDependencies=no',
		'Conflicts=umount.target',
		'Before=umount.target',
		'',
		'[Mount]',
		`What=${options.image}`,
		`Where=${options.mountPoint}`,
		'Type=ext4',
		// Setuid files and device nodes on a tenant-written filesystem are never honoured.
		'Options=loop,nosuid,nodev,noatime',
		'',
	].join('\n');
}

/**
 * Make sure the disk image exists: a sparse file of `sizeMb` with an ext4 filesystem on it. An
 * existing image is kept as it is (its files are the person's); only a missing one is created, into
 * a temporary name first, so a failed `mkfs` never leaves a half-made image behind.
 */
export async function ensureHomeDisk(options: {
	runner: CommandRunner;
	mkfsPath: string;
	image: string;
	sizeMb: number;
	id: string;
}): Promise<{ created: boolean }> {
	const existing = await fs.lstat(options.image).catch(() => null);
	if (existing) {
		if (!existing.isFile() || existing.isSymbolicLink())
			throw new ValidationError(`${options.image} is not a regular file; refusing to mount it`);
		return { created: false };
	}
	const temp = `${options.image}.new`;
	await fs.rm(temp, { force: true });
	const handle = await fs.open(temp, 'wx', 0o600);
	try {
		await handle.truncate(options.sizeMb * 1024 * 1024);
	} finally {
		await handle.close();
	}
	const result = await options.runner.run([
		options.mkfsPath,
		'-q',
		'-F',
		// No root reservation: the whole disk is the person's.
		'-m',
		'0',
		'-L',
		'yoal-home',
		'-E',
		'lazy_itable_init=1,lazy_journal_init=1',
		temp,
	]);
	if (result.code !== 0) {
		await fs.rm(temp, { force: true });
		const detail = result.stderr.trim() || result.stdout.trim() || 'no output';
		throw new Error(`Could not create the cloud shell disk for ${options.id}: mkfs.ext4 failed (${result.code}): ${detail}`);
	}
	await fs.rename(temp, options.image);
	return { created: true };
}

/** True when `mountPoint` is a mount of its own (its device differs from its parent's). */
export async function isMounted(mountPoint: string, parent: string): Promise<boolean> {
	const [inner, outer] = await Promise.all([fs.stat(mountPoint).catch(() => null), fs.stat(parent).catch(() => null)]);
	return Boolean(inner && outer && inner.dev !== outer.dev);
}
